export function getDayFocus(day, lang = 'en', regime = 'CALM') {
  if (day >= 21) {
    return lang === 'hi'
      ? 'दिन 21 पूरा! अपनी रिपोर्ट टैब में 9 आदतों का विश्लेषण देखें।'
      : 'Day 21 complete! Open the Report tab to review all 9 habits and your personal rules.';
  }
  if (regime === 'CRASH') {
    return lang === 'hi'
      ? 'बाज़ार में तेज़ गिरावट है। घबराहट के फ़ैसले से बचें और अपने शुरुआती प्लान को याद रखें।'
      : 'High volatility crash window: pause before panic-selling and compare against your onboarding plan.';
  }
  if (regime === 'HYPE') {
    return lang === 'hi'
      ? 'अफ़वाह या तेज़ उछाल पर प्रतिक्रिया देने से पहले कंपनी के फ़ंडामेंटल्स ⓘ ज़रूर देखें।'
      : 'Hype window: inspect Fundamentals ⓘ and 3-year sales before chasing any fast-moving rumour stock.';
  }
  if (regime === 'RECOVERY') {
    return lang === 'hi'
      ? 'बाज़ार सँभल रहा है — ज़्यादा कर्ज़ वाली कंपनियों के समाचार और पोर्टफ़ोलियो संतुलन पर ध्यान दें।'
      : 'Recovery phase: watch how high-debt companies react to credit news and check portfolio balance.';
  }
  return lang === 'hi'
    ? 'शांत बाज़ार में बिना जल्दबाज़ी के फ़ंडामेंटल्स ⓘ पढ़ें और ओवरट्रेडिंग से बचें।'
    : 'Calm market: take your time reading Fundamentals ⓘ and avoid unnecessary quick flips.';
}

